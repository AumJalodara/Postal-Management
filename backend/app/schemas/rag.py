"""
Pydantic Schemas for RAG (Retrieval-Augmented Generation) API.

Follows existing project conventions:
- ApiResponse[T] wrapper for all responses
- Field validation with clear constraints
- Consistent error handling
"""

from typing import List, Optional
from pydantic import BaseModel, Field


# Request validation constants
RAG_MAX_QUERY_LENGTH = 1000
RAG_MIN_TOP_K = 1
RAG_MAX_TOP_K = 20
RAG_DEFAULT_TOP_K = 5
RAG_VALID_MODES = {"hybrid", "lexical", "dense"}


class RAGRequest(BaseModel):
    """Request schema for POST /api/v1/postal/ask."""
    query: str = Field(
        ...,
        min_length=1,
        max_length=RAG_MAX_QUERY_LENGTH,
        description="Natural language question about postal regulations."
    )
    top_k: int = Field(
        default=RAG_DEFAULT_TOP_K,
        ge=RAG_MIN_TOP_K,
        le=RAG_MAX_TOP_K,
        description="Number of source documents to retrieve (1-20)."
    )
    retrieval_mode: str = Field(
        default="hybrid",
        description="Retrieval strategy: 'hybrid' (default), 'lexical', or 'dense'."
    )


class CitationDetail(BaseModel):
    """A single citation mapping a reference marker to an actual retrieved chunk."""
    citation_id: int = Field(..., description="Citation reference number (e.g., 1 for [1]).")
    document_id: str = Field(..., description="Source document ID (e.g., 'DOC1', 'DOC2').")
    document_title: str = Field(..., description="Full document title.")
    chunk_id: str = Field(..., description="Unique chunk identifier.")
    page: int = Field(..., description="Start page number in the source document.")
    source_pages: List[int] = Field(..., description="All pages spanned by this chunk.")
    legal_reference: str = Field(..., description="Legal reference (e.g., 'Section 9', 'Rule 5').")
    extracted_text: str = Field(default="", description="Actual retrieved text from the corpus.")
    retrieval_score: float = Field(default=0.0, description="Relevance score of the chunk.")
    retrieval_mode: Optional[str] = Field(default=None, description="Retrieval mode used for this chunk.")
    heading: Optional[str] = Field(default=None, description="Section or rule heading/title.")
    clean_text: Optional[str] = Field(default=None, description="Authoritative clean statutory text.")
    ocr_anomaly: bool = Field(default=False, description="Flag indicating OCR quality anomaly.")
    anomaly_note: Optional[str] = Field(default=None, description="Note on OCR anomaly if applicable.")


class RAGResponse(BaseModel):
    """Response schema for POST /api/v1/postal/ask."""
    query: str = Field(..., description="The original user query.")
    answer: str = Field(..., description="AI-generated explanation grounded in official sources.")
    citations: List[CitationDetail] = Field(
        default_factory=list,
        description="Citations mapping [N] markers to actual retrieved chunks."
    )
    retrieved_chunks: int = Field(..., description="Number of chunks retrieved.")
    grounded: bool = Field(..., description="Whether the answer is grounded in retrieved evidence.")
    insufficient_evidence: bool = Field(
        ...,
        description="True if retrieval returned no results for the query."
    )
    retrieval_mode: str = Field(..., description="Retrieval mode used.")
    has_invalid_citations: bool = Field(
        default=False,
        description="True if the LLM generated citation markers not in the source map."
    )
    invalid_citation_ids: List[int] = Field(
        default_factory=list,
        description="List of invalid citation IDs generated by the LLM (if any)."
    )
